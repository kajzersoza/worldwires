export function parseMaintenanceCSV(csvText: string): MaintenanceRecord[] {
  const lines = csvText.split(/\r?\n/).map(l => l.trim()).filter(Boolean);
  if (lines.length <= 1) return [];

  const records: MaintenanceRecord[] = [];
  const seenIds = new Set<string>();

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i];
    // Split by comma taking care of potential commas inside fields
    const parts: string[] = [];
    let cur = '';
    let inQuotes = false;
    for (let c = 0; c < line.length; c++) {
      const ch = line[c];
      if (ch === '"') {
        inQuotes = !inQuotes;
      } else if (ch === ',' && !inQuotes) {
        parts.push(cur.trim());
        cur = '';
      } else {
        cur += ch;
      }
    }
    parts.push(cur.trim());

    const inspectionId = parts[0]?.trim() || `insp_${i}_${Date.now()}`;
    const itemId = parts[1]?.trim() || '';
    const status = parts[2]?.trim() || 'Pass';
    const description = parts[3]?.trim() || '';
    const changeItem = parts[4]?.trim() || '';
    const date = parts[5]?.trim() || '';
    const dateNext = parts[6]?.trim() || '';

    if (!itemId) continue;

    // Deduplicate identical inspectionId rows if any
    let uniqueId = inspectionId;
    if (seenIds.has(uniqueId)) {
      uniqueId = `${uniqueId}_${i}`;
    }
    seenIds.add(uniqueId);

    records.push({
      inspectionId: uniqueId,
      itemId,
      status,
      description,
      changeItem,
      date,
      dateNext,
    });
  }

  return records;
}

